#!/usr/bin/env python3
"""Extracts shellCommandValidationError from ShellToolProvider.kt and its constants from ShellClient.kt.

ShellToolProvider.kt is a 763-line transport-coupled object. The only pure-logic piece
needed for validation testing is shellCommandValidationError. The two constants live
in the transport-heavy ShellClient.kt.

Usage: python3 extract_validation.py <ShellToolProvider.kt> <ShellClient.kt> <out.kt>
"""
import sys

FUNCTION_MARKER = "private fun shellCommandValidationError("
CONSTANTS = [
    "const val SHELL_COMMAND_MAX_BYTES",
    "const val SHELL_WORKDIR_MAX_BYTES",
]

HEADER = """\
// GENERATED by extract_validation.py -- do not edit.
//
// shellCommandValidationError is copied from ShellToolProvider.kt and its constants
// from ShellClient.kt so the shell-command-validation golden stand can compile the real logic.
package com.newoether.agora.tool

"""


def extract_constant(lines, marker):
    for i, line in enumerate(lines):
        if marker in line:
            return [line if line.endswith("\n") else line + "\n"]
    raise SystemExit(f"error: {marker} not found")


def extract_function(lines, marker):
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")
    
    # Make the function internal (was private in the original)
    # Replace "private fun" with "internal fun"
    extracted_lines = lines[start:start + 1].copy()
    extracted_lines[0] = extracted_lines[0].replace("private fun", "internal fun")
    
    # Find the end of the function - look for closing brace at column 0
    # The function has a when expression that spans multiple lines
    end = None
    brace_depth = 0
    for i in range(start, len(lines)):
        line = lines[i]
        # Count braces (simple approach for this specific function)
        brace_depth += line.count("{") - line.count("}")
        if i > start and brace_depth <= 0:
            end = i
            break
    if end is None:
        raise SystemExit(f"error: closing brace of {marker} not found")
    return extracted_lines + lines[start + 1:end + 1]


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    tool_path, client_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    
    with open(tool_path) as f:
        tool_lines = f.readlines()
    with open(client_path) as f:
        client_lines = f.readlines()

    extracted = []
    # Extract constants from ShellClient.kt
    for marker in CONSTANTS:
        extracted.extend(extract_constant(client_lines, marker))
        extracted.append("\n")
    # Extract the function from ShellToolProvider.kt
    extracted.extend(extract_function(tool_lines, FUNCTION_MARKER))

    with open(out_path, "w") as f:
        f.write(HEADER)
        f.writelines(extracted)
    print(f"extracted {len(extracted)} lines into {out_path}")


if __name__ == "__main__":
    main()