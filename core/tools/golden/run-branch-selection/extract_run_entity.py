#!/usr/bin/env python3
"""Lifts RunEntity out of data/local/RunEntity.kt, verbatim.

RunBranchSelectionIntegrity.kt talks about `RunEntity` and `RunEntity::id`, so the file will not
compile without that type. RunEntity.kt itself also carries the Room `@Entity` catalogue entry,
whose `ForeignKey(entity = ChatEntity::class)` pulls in another entity that cannot compile
host-side.

Retyping the data class would make the stand pin a transcription rather than the declaration the
rest of the app constructs, so the whole `data class` declaration (including its `init` invariants)
is copied out byte for byte. Only the `@PrimaryKey` marker inside it is redirected at the
stand-local stub in PlatformStubs.kt.

Fails loudly if the declaration changes shape, so the stand can never drift onto a stale copy.
"""

import io
import sys

HEADER = """package com.newoether.agora.data.local

// GENERATED by extract_run_entity.py from
// app/src/main/java/com/newoether/agora/data/local/RunEntity.kt -- do not edit. The declaration
// below is copied verbatim; only the Room marker is pointed at the stand-local stub.
import androidx.room.PrimaryKey
import com.newoether.agora.model.RunEndReason
import com.newoether.agora.model.RunStatus

"""

INVARIANTS = (
    "require((activeSlot == 1) == !status.isTerminal)",
    "require(status.isTerminal == (endedAt != null && endReason != null))",
    "require(status != RunStatus.STOPPING || stopRequestedAt != null)",
)


def main():
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <RunEntity.kt> <out.kt>", file=sys.stderr)
        return 2
    text = io.open(sys.argv[1], encoding="utf-8").read()

    marker = "data class RunEntity("
    at = text.find(marker)
    if at < 0:
        raise SystemExit("error: `data class RunEntity(` not found in RunEntity.kt")

    block = text[at:]
    if not block.rstrip().endswith("}"):
        raise SystemExit("error: unexpected RunEntity tail; the extractor would drift")
    for invariant in INVARIANTS:
        if invariant not in block:
            raise SystemExit(f"error: RunEntity invariant changed: {invariant}")

    io.open(sys.argv[2], "w", encoding="utf-8").write(HEADER + block.rstrip() + "\n")
    print(f"extracted RunEntity into {sys.argv[2]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
