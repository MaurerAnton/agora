#!/usr/bin/env python3
"""Extracts the stable-id check of CustomProviderIdentityPolicy.

CustomProviderConfig reads its identity through `CustomProviderIdentityPolicy::isStableId`, but
CustomProviderIdentity.kt also owns conversation-model and SnackbarEvent helpers. This copies the
id pattern and the check verbatim into a stand-alone object so the name policy and the config
compile against the real regex.

Usage: python3 extract_identity.py <CustomProviderIdentity.kt> <out.kt>
"""
import sys

REGIONS = [
    "    private const val STABLE_ID_PATTERN",
    "    private val stableIdPattern = Regex(",
    "    fun isStableId(value: String): Boolean = stableIdPattern.matches(value.trim())",
]

HEADER = """\
// GENERATED by extract_identity.py from CustomProviderIdentity.kt -- do not edit.
//
// The stable-id pattern and isStableId are copied verbatim (visibility widened, member
// indentation removed) so CustomProviderConfig.kt compiles unchanged against them.
package com.newoether.agora.data

object CustomProviderIdentityPolicy {

"""


def extract_region(lines, marker):
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")

    paren = 0
    brace = 0
    seen_brace = False
    end = None
    for i in range(start, len(lines)):
        for char in lines[i]:
            if char == "{":
                brace += 1
                seen_brace = True
            elif char == "}":
                brace -= 1
            elif char in "([":
                paren += 1
            elif char in ")]":
                paren -= 1
        if seen_brace:
            if brace == 0:
                end = i
                break
            continue
        if paren != 0:
            continue
        stripped = lines[i].rstrip()
        if stripped.endswith(("=", ",")):
            continue
        next_line = lines[i + 1].lstrip() if i + 1 < len(lines) else ""
        if next_line.startswith(("?", "+", ".", "-", '"')):
            continue
        end = i
        break
    if end is None:
        raise SystemExit(f"error: end of {marker} not found")

    region = []
    for line in lines[start : end + 1]:
        if line.startswith("    "):
            line = line[4:]
        if line.startswith("private const val "):
            line = "internal const val " + line[len("private const val "):]
        elif line.startswith("private val "):
            line = "internal val " + line[len("private val "):]
        region.append(line)
    return region


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_identity.py <CustomProviderIdentity.kt> <out.kt>", file=sys.stderr)
        return 2
    lines = open(sys.argv[1], encoding="utf-8").read().split("\n")
    blocks = ["\n".join(extract_region(lines, marker)) for marker in REGIONS]
    text = "\n\n".join(blocks)
    for name in ("STABLE_ID_PATTERN", "stableIdPattern", "isStableId"):
        if name not in text:
            raise SystemExit(f"error: {name} missing from the extracted region")
    with open(sys.argv[2], "w", encoding="utf-8") as handle:
        handle.write(HEADER + text + "\n}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())