#!/usr/bin/env python3
"""Extracts the request models of EmbeddingClient.kt.

The client wires coroutines and HttpClient and cannot compile standalone, but the golden stand
runs the REAL @Serializable request declarations: this script copies the exact source region
verbatim (EmbeddingRequest through BatchEmbeddingRequest), widening `private` to `internal` so
the trace dump can serialize them. The response parsing is a small inline block transcribed by
the driver, line for line, like the other stands' local functions.

Usage: python3 extract_embedding_models.py <EmbeddingClient.kt> <out.kt>
"""
import sys

START_CLASS = "private data class EmbeddingRequest("
END_CLASS = "private data class BatchEmbeddingRequest("
EXPECTED = ["EmbeddingRequest", "BatchEmbeddingRequest"]

HEADER = """\
// GENERATED by extract_embedding_models.py from EmbeddingClient.kt -- do not edit.
//
// The request models are copied verbatim from the client file, which cannot be compiled
// standalone (coroutines + HttpClient); the embedding golden stand pins them here. The only
// transformation is widening `private data class` to `internal data class`.
package com.newoether.agora.api

import kotlinx.serialization.Serializable

"""


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_embedding_models.py <EmbeddingClient.kt> <out.kt>", file=sys.stderr)
        return 2
    source_path, out_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().split("\n")

    start = None
    for i, line in enumerate(lines):
        if START_CLASS in line:
            if i == 0 or lines[i - 1].strip() != "@Serializable":
                raise SystemExit(f"error: no @Serializable directly above {START_CLASS}")
            start = i - 1
            break
    if start is None:
        raise SystemExit(f"error: {START_CLASS} not found")

    # Take both classes: from EmbeddingRequest to the closing paren of BatchEmbeddingRequest.
    end = None
    seen_batch = False
    for i in range(start, len(lines)):
        if END_CLASS in lines[i]:
            seen_batch = True
        if seen_batch and lines[i].strip() == ")":
            end = i
            break
    if end is None:
        raise SystemExit(f"error: closing paren of {END_CLASS} not found")

    region = []
    for line in lines[start : end + 1]:
        if line.startswith("private data class "):
            line = "internal data class " + line[len("private data class "):]
        region.append(line)
    text = "\n".join(region)
    for cls in EXPECTED:
        if f"data class {cls}(" not in text:
            raise SystemExit(f"error: {cls} is not inside the extracted region")

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(HEADER + "\n".join(region) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
