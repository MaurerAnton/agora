#!/usr/bin/env python3
"""Lifts TaskEntity out of data/local/ChatEntities.kt, verbatim.

TaskSchedule.kt defines `hasSchedule()` as an extension on TaskEntity, so the file will not
compile without that type. ChatEntities.kt itself is a Room entity catalogue importing
androidx.room.* plus model types, none of which the schedule logic touches, so the whole file
cannot compile host-side.

Retyping TaskEntity would make the stand pin a transcription rather than the declaration the rest
of the app reads, so it is copied out byte for byte. Only the two Room annotations are redirected
at stand-local marker declarations, which are platform types with no behaviour.

Fails loudly if the declaration changes shape, so the stand can never drift onto a stale copy.
"""

import re
import sys

HEADER = """package com.newoether.agora.data.local

// GENERATED by extract_task_entity.py from
// app/src/main/java/com/newoether/agora/data/local/ChatEntities.kt -- do not edit. The declaration
// below is copied verbatim; only the Room markers are pointed at the stand-local stubs.
import androidx.room.Entity
import androidx.room.PrimaryKey

"""

OWNED_BY_HEADER = re.compile(r"^(?:@|/\*\*|\*/|\*|//)")


def skip_literal(text, at):
    quote = text[at]
    at += 1
    while at < len(text):
        if text[at] == "\\":
            at += 2
            continue
        if text[at] == quote:
            return at + 1
        at += 1
    return at


def declaration_end(text, start):
    paren = 0
    brace = 0
    at = start
    while at < len(text):
        char = text[at]
        if char == '"':
            at = skip_literal(text, at)
            continue
        if text.startswith("//", at):
            newline = text.find("\n", at)
            at = len(text) if newline < 0 else newline
            continue
        if text.startswith("/*", at):
            close = text.find("*/", at + 2)
            at = len(text) if close < 0 else close + 2
            continue
        if char == "(":
            paren += 1
        elif char == ")":
            paren -= 1
            if paren == 0 and brace == 0:
                probe = at + 1
                while probe < len(text) and text[probe] in " \t":
                    probe += 1
                if probe >= len(text) or text[probe] == "\n":
                    return at + 1
        elif char == "{":
            brace += 1
        elif char == "}":
            brace -= 1
            if brace == 0:
                return at + 1
        at += 1
    raise SystemExit("error: unterminated declaration in ChatEntities.kt")


def extract(text, name):
    match = re.search(r"^(?:data |internal data |public data )?class " + re.escape(name) + r"\b",
                      text, re.MULTILINE)
    if match is None:
        raise SystemExit(f"error: declaration `{name}` not found in ChatEntities.kt")

    lines = text[: match.start()].split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    owned = 0
    while lines:
        candidate = lines[-1]
        if not (OWNED_BY_HEADER.match(candidate.strip()) or candidate.lstrip().startswith("*")):
            break
        owned += 1
        lines.pop()
    if owned == 0:
        raise SystemExit(f"error: `{name}` has no annotation block; the extractor would drift")

    start = match.start()
    for _ in range(owned):
        start = text.rfind("\n", 0, start - 1) + 1
    return text[start : declaration_end(text, match.end())]


def main():
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <ChatEntities.kt> <out.kt>", file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as handle:
        text = handle.read()

    block = extract(text, "TaskEntity")
    with open(sys.argv[2], "w", encoding="utf-8") as handle:
        handle.write(HEADER + block.rstrip() + "\n")
    print(f"extracted TaskEntity into {sys.argv[2]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())