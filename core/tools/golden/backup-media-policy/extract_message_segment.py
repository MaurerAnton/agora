#!/usr/bin/env python3
"""Lifts the message-segment declarations out of model/ChatMessage.kt, verbatim.

NativeBackupMediaPolicy.kt needs MessageSegment, ToolImageAttachment and StreamingTextDelta.
Those live in model/ChatMessage.kt, which cannot compile host-side: it is annotated with
androidx.compose.runtime.Immutable and its neighbours (ChatMessage, ChatConversation, the
Participant/MessageStatus enums, the display-mode objects) are UI state, not policy inputs.

Retyping the three declarations would make the stand pin the transcription instead of the
implementation, so they are copied out of the app tree byte for byte. Only the Compose marker
annotation is replaced (by a stub in the stand), which is a platform type: @Immutable is a pure
marker with no effect on the JSON shape these classes produce.

Fails loudly if any of the three declarations changes shape, so the stand can never silently
drift onto a stale copy.
"""

import re
import sys

WANTED = ("ToolImageAttachment", "StreamingTextDelta", "MessageSegment")

HEADER = """package com.newoether.agora.model

// GENERATED by extract_message_segment.py from app/src/main/java/com/newoether/agora/model/
// ChatMessage.kt -- do not edit. The declarations below are copied verbatim.
import kotlinx.serialization.Serializable
import kotlinx.serialization.Transient
import kotlinx.serialization.json.JsonObject

"""


DECLARATION = r"^(?:data |internal data |public data )?class {}\b"
# Lines that belong to the declaration's own annotation/KDoc block rather than to whatever sits
# above it: an annotation, a KDoc opener or continuation, or a line comment.
OWNED_BY_HEADER = re.compile(r"^(?:@|/\*\*|\*/|\*|//)")


def skip_literal(text: str, at: int) -> int:
    """Returns the index just past the string literal starting at `at`."""
    quote = text[at]
    at += 1
    while at < len(text):
        if text[at] == "\\":
            at += 2
            continue
        if text[at] == quote:
            return at + 1
        at += 1
    return at


def declaration_end(text: str, start: int, name: str) -> int:
    """Returns the index just past the declaration body starting at `start`.

    A Kotlin data class with no body ends at the primary constructor's closing paren, not at a
    brace -- scanning for `{` alone would run straight through it into the next class.
    """
    paren = 0
    brace = 0
    at = start
    while at < len(text):
        char = text[at]
        if char == '"':
            at = skip_literal(text, at)
            continue
        if text.startswith("//", at):
            newline = text.find("\n", at)
            at = len(text) if newline < 0 else newline
            continue
        if text.startswith("/*", at):
            close = text.find("*/", at + 2)
            at = len(text) if close < 0 else close + 2
            continue
        if char == "(":
            paren += 1
        elif char == ")":
            paren -= 1
            if paren == 0 and brace == 0:
                probe = at + 1
                while probe < len(text) and text[probe] in " \t":
                    probe += 1
                if probe >= len(text) or text[probe] == "\n":
                    return at + 1
        elif char == "{":
            brace += 1
        elif char == "}":
            brace -= 1
            if brace == 0:
                return at + 1
        at += 1
    raise SystemExit(f"error: unterminated declaration `{name}` in ChatMessage.kt")


def extract(text: str, name: str) -> str:
    """Returns `name` with its own annotations and KDoc, through its closing brace."""
    declaration = DECLARATION.format(re.escape(name))
    match = re.search(declaration, text, re.MULTILINE)
    if match is None:
        raise SystemExit(f"error: declaration `{name}` not found in ChatMessage.kt")

    # Walk back over the annotation/KDoc block that belongs to THIS declaration; stop at the
    # first line that closes something else, so neighbouring classes are never pulled in.
    lines = text[: match.start()].split("\n")
    if lines and lines[-1] == "":
        lines.pop()  # the newline that terminates the last preceding line
    owned = 0
    while lines:
        candidate = lines[-1]
        if not (OWNED_BY_HEADER.match(candidate.strip()) or candidate.lstrip().startswith("*")):
            break
        owned += 1
        lines.pop()
    if owned == 0:
        raise SystemExit(f"error: `{name}` has no annotation block; the extractor would drift")

    # Walk back `owned` newlines in the original text; re-joining the split would lose a
    # character and silently slice the wrong range.
    start = match.start()
    for _ in range(owned):
        start = text.rfind("\n", 0, start - 1) + 1

    return text[start : declaration_end(text, match.end(), name)]


def main() -> int:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <ChatMessage.kt> <out.kt>", file=sys.stderr)
        return 2
    source, out = sys.argv[1], sys.argv[2]
    with open(source, encoding="utf-8") as handle:
        text = handle.read()

    pieces = [HEADER]
    for name in WANTED:
        block = extract(text, name)
        # The Compose marker is substituted by a stand-local stub; nothing else may change.
        block = block.replace("@Immutable\n", "@androidx.compose.runtime.Immutable\n")
        pieces.append(block + "\n\n")

    with open(out, "w", encoding="utf-8") as handle:
        handle.write("".join(pieces).rstrip() + "\n")
    print(f"extracted {', '.join(WANTED)} into {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())