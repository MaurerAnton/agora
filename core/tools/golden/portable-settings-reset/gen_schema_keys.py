#!/usr/bin/env python3
"""Regenerates the settings-schema key list used by the portable-settings-reset stand.

The list is read out of data/SettingsPreferenceSchema.kt so the golden stand can seed the
preference store with the real schema instead of a hand-written copy. Run it after the schema
changes.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
SCHEMA = os.path.join(ROOT, "app", "src", "main", "java", "com", "newoether", "agora", "data",
                       "SettingsPreferenceSchema.kt")
OUT = os.path.join(HERE, "SchemaKeys.kt")

PATTERN = re.compile(
    r'internal val ([A-Z0-9_]+)\s*=\s*\n?\s*[a-zA-Z]+PreferencesKey\(\s*"([^"]+)"',
    re.M,
)


def main() -> int:
    source = open(SCHEMA, encoding="utf-8").read()
    pairs = PATTERN.findall(source)
    if not pairs:
        print("error: no keys found in %s" % SCHEMA, file=sys.stderr)
        return 2
    lines = [
        "// GENERATED by gen_schema_keys.py from data/SettingsPreferenceSchema.kt -- do not edit.",
        "//",
        "// The names of every settings key, so the golden stand can seed the preference store",
        "// with the full schema instead of a hand-written list.",
        "package portable.settings.reset.golden",
        "",
        "internal val SCHEMA_KEY_NAMES: List<String> = listOf(",
    ]
    for name, literal in pairs:
        lines.append('    com.newoether.agora.data.%s.name,  // "%s"' % (name, literal))
    lines.append(")")
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print("Wrote %d keys to %s" % (len(pairs), OUT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
