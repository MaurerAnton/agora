#!/usr/bin/env python3
"""Lifts the recovery module's shared declarations out of the app tree.

Three pieces are needed and none compiles on its own:

* `data/local/ChatEntities.kt` — `MessageEntity` and `MessageStreamCheckpoint` live in a file
  that also declares the other tables and the type converters, so both classes are copied out
  here byte for byte (annotations included) and Room is satisfied by the stand-local stubs.
* `data/local/ChatDao.kt` — `encodeSelectionMap` is the branch-projection encoder the recovery
  body calls; only its `internal` visibility widening is needed for the driver.
* `data/local/ChatDaoRuntimeRecovery.kt` compiles verbatim (the driver shares its module, so
  `internal` visibility needs no widening).
"""
