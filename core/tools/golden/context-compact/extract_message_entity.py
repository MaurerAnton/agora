#!/usr/bin/env python3
"""Lifts MessageEntity out of data/local/ChatEntities.kt.

The compact-graph file needs the message row type, and ChatEntities.kt also declares the other
tables and the type converters, so the class is copied out here byte for byte (annotations
included) and Room is satisfied by the stand-local stubs.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
APP = os.path.join(ROOT, "app", "src", "main", "java", "com", "newoether", "agora")
OUT = os.path.join(HERE, "build")

HEADER = """\
// GENERATED by extract_message_entity.py from data/local/ChatEntities.kt -- do not edit.
//
// MessageEntity is copied verbatim; the Room annotations are satisfied by the stand-local stubs
// (Room is a persistence framework: the annotations have no runtime behaviour the compact graph
// transactions can observe).
package com.newoether.agora.data.local

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import com.newoether.agora.model.MessageStatus
import com.newoether.agora.model.Participant

"""


def extract(text: str, name: str) -> str:
    lines = text.split("\n")
    declaration = "data class %s(" % name
    declaration_index = next(
        (i for i, line in enumerate(lines) if line.startswith(declaration)), None)
    if declaration_index is None:
        raise SystemExit("error: %s not found" % name)
    # Walk back over the annotation block directly above the declaration.
    probe = declaration_index
    while probe > 0:
        previous = lines[probe - 1]
        if previous.strip() == "" or previous.strip() == "}":
            break
        if previous.startswith("@") or previous.startswith("    ") or previous.strip() in (")", "],"):
            probe -= 1
            continue
        break
    # Search for the end from the declaration itself: the annotation block ends with a col-0 `)`
    # that would otherwise terminate the extract before the class starts. A data class body ends
    # with `}`; a bodyless one ends with the closing parenthesis of its parameter list.
    end = next(
        (i for i in range(declaration_index + 1, len(lines)) if lines[i] in ("}", ")")), None)
    if end is None:
        raise SystemExit("error: end of %s not found" % name)
    return "\n".join(lines[probe:end + 1])


def main() -> int:
    os.makedirs(OUT, exist_ok=True)
    entities = open(os.path.join(APP, "data", "local", "ChatEntities.kt"), encoding="utf-8").read()
    with open(os.path.join(OUT, "MessageEntity.kt"), "w", encoding="utf-8") as handle:
        handle.write(HEADER + extract(entities, "MessageEntity") + "\n")
    print("Extracted MessageEntity")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
