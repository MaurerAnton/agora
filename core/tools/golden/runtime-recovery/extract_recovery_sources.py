def widen(text: str) -> str:
    out = []
    for line in text.split("\n"):
        stripped = line.lstrip()
        if stripped.startswith("internal "):
            indent = line[: len(line) - len(stripped)]
            line = indent + stripped[len("internal "):]
        out.append(line)
    return "\n".join(out)


def extract_class(text: str, name: str) -> str:
    lines = text.split("\n")
    declaration = "data class %s(" % name
    declaration_index = next(
        (i for i, line in enumerate(lines) if line.startswith(declaration)), None)
    if declaration_index is None:
        raise SystemExit("error: %s not found" % name)
    start = declaration_index
    # Walk back over the annotation block directly above the declaration.
    probe = start
    while probe > 0:
        previous = lines[probe - 1]
        if previous.strip() == "" or previous.strip() == "}":
            break
        if previous.startswith("@") or previous.startswith("    ") or previous.strip() in (")", "],"):
            probe -= 1
            continue
        break
    start = probe
    # Search for the end from the declaration itself: the annotation block ends with a col-0 `)`
    # that would otherwise terminate the extract before the class starts. A data class body ends
    # with `}`; a bodyless one ends with the closing parenthesis of its parameter list.
    end = next((i for i in range(declaration_index + 1, len(lines)) if lines[i] in ("}", ")")), None)
    if end is None:
        raise SystemExit("error: end of %s not found" % name)
    return "\n".join(lines[start:end + 1])


def extract_function(text: str, name: str) -> str:
    lines = text.split("\n")
    signature = "internal fun %s(" % name
    start = next((i for i, line in enumerate(lines) if line.startswith(signature)), None)
    if start is None:
        raise SystemExit("error: %s not found" % name)
    if lines[start].rstrip().endswith("="):
        # Expression body: the continuation is the indented block up to the next blank line.
        end = start + 1
        while end + 1 < len(lines) and lines[end + 1].strip() != "":
            end += 1
        return "\n".join(lines[start:end + 1])
    end = next((i for i in range(start, len(lines)) if lines[i] == "}"), None)
    if end is None:
        raise SystemExit("error: end of %s not found" % name)
    return "\n".join(lines[start:end + 1])


def main() -> int:
    os.makedirs(OUT, exist_ok=True)

    entities = open(os.path.join(APP, "data", "local", "ChatEntities.kt"), encoding="utf-8").read()
    lifted = "\n\n".join(
        extract_class(entities, name) for name in ("MessageEntity", "MessageStreamCheckpoint")
    )
    with open(os.path.join(OUT, "MessageEntities.kt"), "w", encoding="utf-8") as handle:
        handle.write(ENTITY_HEADER + lifted + "\n")

    dao = open(os.path.join(APP, "data", "local", "ChatDao.kt"), encoding="utf-8").read()
    encoder = extract_function(dao, "encodeSelectionMap")
    with open(os.path.join(OUT, "EncodeSelectionMap.kt"), "w", encoding="utf-8") as handle:
        handle.write(DAO_HEADER + encoder + "\n")

    recovery = open(os.path.join(APP, "data", "local", "ChatDaoRuntimeRecovery.kt"),
                    encoding="utf-8").read()
    with open(os.path.join(OUT, "ChatDaoRuntimeRecovery.kt"), "w", encoding="utf-8") as handle:
        handle.write(recovery)

    print("Extracted MessageEntity, MessageStreamCheckpoint, encodeSelectionMap and the recovery body")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
