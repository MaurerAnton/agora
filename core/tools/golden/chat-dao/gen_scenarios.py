HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "scenarios")


def write(name: str, scenario: dict) -> None:
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".json"), "w", encoding="utf-8") as handle:
        json.dump(scenario, handle, ensure_ascii=False, indent=2)
        handle.write("\n")


def conv(cid: str, **kw) -> dict:
    row = {
        "id": cid,
        "title": cid,
        "lastUpdated": 0,
        "dataChangedAt": 0,
        "origin": "user",
        "graduated": False,
        "draftText": "",
        "hasUnreadGeneration": False,
        "isPinned": False,
    }
    row.update(kw)
    return row


def run(rid: str, cid: str, status: str = "COMPLETED", **kw) -> dict:
    row = {
        "id": rid,
        "conversationId": cid,
        "status": status,
        "activeSlot": None if status in ("COMPLETED", "STOPPED", "FAILED") else 1,
        "startedAt": 0,
        "lastCheckpointAt": 0,
        "currentPass": 0,
        "legacyAmbiguous": False,
    }
    if status in ("COMPLETED", "STOPPED", "FAILED"):
        row["endedAt"] = 0
        row["endReason"] = "MODEL_COMPLETED" if status == "COMPLETED" else (
            "USER_STOPPED" if status == "STOPPED" else "PROVIDER_ERROR"
        )
    if status == "STOPPING":
        row["stopRequestedAt"] = 0
    row.update(kw)
    return row


def msg(mid: str, cid: str, rid: str, **kw) -> dict:
    row = {
        "id": mid,
        "conversationId": cid,
        "text": "",
        "images": [],
        "tokenCount": 0,
        "status": "SUCCESS",
        "participant": "MODEL",
        "timestamp": 0,
        "runId": rid,
        "runSequence": -1,
    }
    row.update(kw)
    return row


def emb(eid: int, mid: str, model: str, payload_b64: str, **kw) -> dict:
    row = {
        "id": eid,
        "messageId": mid,
        "modelId": model,
        "embeddingBase64": payload_b64,
        "chunkText": "",
        "dimension": 0,
    }
    row.update(kw)
    return row


def task(tid: str, **kw) -> dict:
    row = {
        "id": tid,
        "name": tid,
        "prompt": "prompt",
        "cronExpr": "",
        "nextRunAt": 0,
        "enabled": True,
        "createdAt": 0,
    }
    row.update(kw)
    return row


def loop(cid: str, **kw) -> dict:
    row = {
        "conversationId": cid,
        "intervalMs": 0,
        "nextFireAt": 0,
        "cycleCount": 0,
        "active": True,
        "revision": 0,
    }
    row.update(kw)
    return row


def settings(cid: str, value: str | None) -> dict:
    return {"conversationId": cid, "settingsJson": value}


def persist(**kw) -> dict:
    row = {
        "id": 0,
        "modelId": None,
        "systemPromptId": None,
        "conversationSettingsJson": None,
        "draftText": "",
        "draftAttachments": None,
    }
    row.update(kw)
    return row


def import_transfer(transfer_id: str, settings_json: str, mode: str = "MERGE", **kw) -> dict:
    row = {"transferId": transfer_id, "settingsJson": settings_json, "mode": mode}
    row.update(kw)
    return row


def step(op: str, **kw) -> dict:
    row = {"op": op}
    row.update(kw)
    return row


