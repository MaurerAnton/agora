#!/usr/bin/env python3
"""Lifts `internal fun InputStream.readToEnd()` verbatim from NativeBackupArchive.kt.

NativeConversationGraphSource.kt drains its entry streams with this extension (the comment in
the app source says reading to the end is what verifies an archive entry), but compiling all of
NativeBackupArchive.kt would drag in the Context/Uri/ParcelFileDescriptor surface this stand
does not substitute. The four-line function is extracted byte-for-byte; only the package line
and the InputStream import are added.
"""
from __future__ import annotations

import os
import sys

HEADER = """// Generated by extract_read_to_end.py from app/src/main/java/com/newoether/agora/data/NativeBackupArchive.kt.
// The function body below is copied byte-for-byte; only the package and import are added here.
package com.newoether.agora.data

import java.io.InputStream

"""


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: extract_read_to_end.py <NativeBackupArchive.kt> <output.kt>")
    source_path, output_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().splitlines(keepends=True)

    start = None
    for index, line in enumerate(lines):
        if line.startswith("internal fun InputStream.readToEnd()"):
            start = index
            break
    if start is None:
        raise SystemExit("readToEnd not found in " + source_path)

    end = None
    for index in range(start, len(lines)):
        if lines[index].rstrip("\n") == "}":
            end = index
            break
    if end is None:
        raise SystemExit("readToEnd closing brace not found")

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8", newline="") as handle:
        handle.write(HEADER)
        handle.write("".join(lines[start : end + 1]))


if __name__ == "__main__":
    main()
