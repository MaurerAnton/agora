#!/usr/bin/env python3
"""Extracts the pure MCP pieces from McpModels.kt and McpProtocolClient.kt.

McpModels.kt itself compiles VERBATIM from the app tree (it only needs the api tool models and
kotlinx), and its private schema projections are copied here verbatim with `private` widened to
`internal` so the trace dump can pin them. From McpProtocolClient.kt — which wires coroutines,
the transport and the data layer — this copies the protocol constants, the version classifier
and parseCallPayload verbatim; class members are lifted to file level.

The JSON-RPC response validation, the negotiation candidate order and the tools/list page
mapping are inline code inside transport-coupled functions; the driver transcribes them line for
line (documented in the stand README).

Usage: python3 extract_mcp_pieces.py <McpModels.kt> <McpProtocolClient.kt> <out.kt>
"""
import sys

MODELS_REGIONS = [
    ("enum class McpConnectionStatus {", 0, False),
    ("data class McpRemoteTool(", 0, False),
    ("data class McpToolDescriptor(", 0, False),
    ("data class McpImagePayload(", 0, False),
    ("data class McpCallPayload(", 0, False),
    ("internal fun publicMcpToolName(serverId: String, remoteName: String): String {", 0, False),
    ("private fun JsonObject.toToolParameters(): ToolParameters {", 0, True),
    ("private fun JsonObject.toWireSchema(type: String): JsonObject {", 0, True),
    ("private fun JsonObject?.toToolProperty(): ToolProperty {", 0, True),
    ("private fun inferSchemaType(schema: JsonObject): String =", 0, True),
    ("internal fun JsonElement.asObjectOrNull(): JsonObject? =", 0, False),
]

CLIENT_REGIONS = [
    ("internal fun isUnsupportedMcpProtocolVersion(error: Throwable): Boolean {", 0, False),
    ("        private const val STREAMABLE_HTTP_PROTOCOL_VERSION", 8, True),
    ("        private const val LEGACY_SSE_PROTOCOL_VERSION", 8, True),
    ("        private const val MAX_TOOL_PAGES", 8, True),
    ("        internal val STREAMABLE_HTTP_PROTOCOL_VERSIONS = listOf(", 8, False),
    ("        private val SUPPORTED_PROTOCOL_VERSIONS", 8, True),
    ("    private fun parseCallPayload(result: JsonObject): McpCallPayload {", 4, True),
]

HEADER = """\
// GENERATED by extract_mcp_pieces.py from McpModels.kt and McpProtocolClient.kt -- do not edit.
//
// The schema projections, the protocol constants, the version classifier and parseCallPayload are
// copied verbatim; only visibility (private -> internal) and the class-member indentation are
// changed so the mcp-protocol golden stand can pin them.
package com.newoether.agora.mcp

import com.newoether.agora.api.ToolDefinition
import com.newoether.agora.api.ToolFunction
import com.newoether.agora.api.ToolParameters
import com.newoether.agora.api.ToolProperty
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonObject
import java.security.MessageDigest

"""


def extract_region(lines, marker, indent, widen):
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")

    paren = 0
    brace = 0
    seen_brace = False
    end = None
    for i in range(start, len(lines)):
        for char in lines[i]:
            if char == "{":
                brace += 1
                seen_brace = True
            elif char == "}":
                brace -= 1
            elif char in "([":
                paren += 1
            elif char in ")]":
                paren -= 1
        if seen_brace:
            if brace == 0:
                end = i
                break
            continue
        if paren != 0:
            continue
        stripped = lines[i].rstrip()
        if stripped.endswith(("=", ",", "&&", "||", "+", "->", "(")):
            continue
        next_stripped = lines[i + 1].lstrip() if i + 1 < len(lines) else ""
        if next_stripped.startswith(("?:", "?.", "&&", "||", "+", ".")):
            continue
        end = i
        break
    if end is None:
        raise SystemExit(f"error: end of {marker} not found")

    prefix = " " * indent
    region = []
    for line in lines[start : end + 1]:
        if line.startswith(prefix):
            line = line[indent:]
        if widen and line.startswith("private fun "):
            line = "internal fun " + line[len("private fun "):]
        elif widen and line.startswith("private const val "):
            line = "internal const val " + line[len("private const val "):]
        elif widen and line.startswith("private val "):
            line = "internal val " + line[len("private val "):]
        region.append(line)
    return region


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: extract_mcp_pieces.py <McpModels.kt> <McpProtocolClient.kt> <out.kt>",
              file=sys.stderr)
        return 2
    models_path, client_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    models = open(models_path, encoding="utf-8").read().split("\n")
    client = open(client_path, encoding="utf-8").read().split("\n")

    blocks = []
    for marker, indent, widen in MODELS_REGIONS:
        blocks.append("\n".join(extract_region(models, marker, indent, widen)))
    for marker, indent, widen in CLIENT_REGIONS:
        blocks.append("\n".join(extract_region(client, marker, indent, widen)))

    text = "\n\n".join(blocks)
    for name in ("toToolParameters", "toWireSchema", "toToolProperty", "inferSchemaType",
                 "isUnsupportedMcpProtocolVersion", "STREAMABLE_HTTP_PROTOCOL_VERSIONS",
                 "parseCallPayload", "MCP_PROTOCOL_NAMED_PLACEHOLDER"):
        if name == "MCP_PROTOCOL_NAMED_PLACEHOLDER":
            continue
        if name not in text:
            raise SystemExit(f"error: {name} missing from the extracted region")

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(HEADER + text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())