#!/usr/bin/env python3
"""Extracts the Gemini stream-side helpers from GeminiProvider.kt.

The provider file cannot be compiled standalone (HTTP client, coroutines, DebugLog), but the
stream golden stand runs the REAL helpers: this script copies the exact source regions verbatim
into a generated file. The only transformation is widening the two `private` helpers
(`extractThoughtTitle`, `JsonObject.stringContent`) to `internal` so the trace dump can call
them; bodies and the two thought-title regexes are untouched.

Usage: python3 extract_gemini_stream_helpers.py <GeminiProvider.kt> <out.kt>
"""
import sys

VAL_MARKERS = [
    "private val THOUGHT_TITLE_BOLD",
]
FUNCTION_MARKERS = [
    "private fun extractThoughtTitle(",
    "private fun JsonObject.stringContent(",
    "internal fun normalizeGeminiFinishReason(",
    "internal fun geminiStreamTermination(",
    "internal fun JsonObject.toGoogleSearchHostedUpdate(",
    "internal fun ApiExecutableCode.toCodeExecutionStart(",
    "internal fun ApiCodeExecutionResult.toCodeExecutionCompletion(",
]

HEADER = """\
// GENERATED by extract_gemini_stream_helpers.py from GeminiProvider.kt -- do not edit.
//
// The stream-side helpers (thought-title extraction, finish-reason normalization, termination,
// hosted-tool projections) are copied verbatim from the provider file, which cannot be compiled
// standalone (Android-only imports); the stream golden stand pins them here. The only change is
// widening `extractThoughtTitle` and `JsonObject.stringContent` from private to internal.
package com.newoether.agora.api.gemini

import com.newoether.agora.api.GenerationError
import com.newoether.agora.api.StreamEvent
import com.newoether.agora.api.util.StreamTermination
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

"""


def extract_vals(lines, marker):
    """Takes the matched `private val` line plus the companion regex line that follows it."""
    for i, line in enumerate(lines):
        if line.startswith(marker):
            region = [line, lines[i + 1]]
            if "THOUGHT_TITLE_HEADING" not in lines[i + 1]:
                raise SystemExit(f"error: expected the heading regex after {marker}")
            return region
    raise SystemExit(f"error: {marker} not found")


def extract_function(lines, marker):
    """Finds the function declaration line for marker and takes it through the function end.

    Unified end detection: once a brace has been opened, the function ends when braces balance;
    before that (expression bodies) it ends when the parentheses balance at a line end that is
    neither an operator nor the start of a continuation line.
    """
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")

    paren = 0
    brace = 0
    seen_brace = False
    end = None
    for i in range(start, len(lines)):
        for char in lines[i]:
            if char == "{":
                brace += 1
                seen_brace = True
            elif char == "}":
                brace -= 1
            elif char in "([":
                paren += 1
            elif char in ")]":
                paren -= 1
        if seen_brace:
            if brace == 0:
                end = i
                break
            continue
        if paren != 0:
            continue
        stripped = lines[i].rstrip()
        if stripped.endswith(("=", ",", "&&", "||", "+", "->")):
            continue
        next_stripped = lines[i + 1].lstrip() if i + 1 < len(lines) else ""
        if next_stripped.startswith(("?:", "?.", "&&", "||", "+", ".")):
            continue  # the expression continues on the next line
        end = i
        break
    if end is None:
        raise SystemExit(f"error: end of {marker} not found")

    region = lines[start : end + 1]
    widened = []
    for line in region:
        if line.startswith("private fun "):
            line = "internal fun " + line[len("private fun "):]
        widened.append(line)
    return widened


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_gemini_stream_helpers.py <GeminiProvider.kt> <out.kt>",
              file=sys.stderr)
        return 2
    source_path, out_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().split("\n")

    blocks = []
    for marker in VAL_MARKERS:
        blocks.append("\n".join(extract_vals(lines, marker)))
    for marker in FUNCTION_MARKERS:
        blocks.append("\n".join(extract_function(lines, marker)))

    text = "\n\n".join(blocks)
    for name in ("THOUGHT_TITLE_BOLD", "extractThoughtTitle", "normalizeGeminiFinishReason",
                 "geminiStreamTermination", "toGoogleSearchHostedUpdate"):
        if name not in text:
            raise SystemExit(f"error: {name} missing from the extracted region")

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(HEADER + text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
