#!/usr/bin/env python3
"""Lifts the import pieces NativeConversationGraphImporter.kt needs from DataImporter.kt.

DataImporter.kt as a whole drags in the whole import composition root (SettingsManager,
MemoryManager, the transfer coordinator, the archive restore path) that the graph importer never
touches. What it needs is:

  * sanitizeImportedTask / sanitizeImportedLoop / sanitizeImportedConversation — the three
    top-level helpers, copied byte-for-byte including their KDoc;
  * DataImporter.ImportStrategy — the nested enum, copied byte-for-byte inside a class
    DataImporter wrapper (the importer references it as a nested type).

The output is generated into build/ so DataImporter.kt stays the single source of truth.
"""
from __future__ import annotations

import os
import sys

HEADER = """// Generated by extract_import_pieces.py from app/src/main/java/com/newoether/agora/data/DataImporter.kt.
// The function bodies and the enum below are copied byte-for-byte; only the package line and the
// imports the pieces use are added here.
package com.newoether.agora.data

import com.newoether.agora.automation.LoopPolicy
import com.newoether.agora.data.local.ChatEntity
import com.newoether.agora.data.local.LoopEntity
import com.newoether.agora.data.local.TaskEntity

"""


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: extract_import_pieces.py <DataImporter.kt> <output.kt>")
    source_path, output_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().splitlines(keepends=True)

    # 1. The three sanitize helpers: from the KDoc above sanitizeImportedTask to the closing
    #    brace of sanitizeImportedConversation (the next top-level declaration after it).
    task_doc = None
    for index, line in enumerate(lines):
        if line.startswith("/**") and index + 1 < len(lines) and \
                lines[index + 1].startswith(" * Imported automations are content"):
            task_doc = index
            break
    if task_doc is None:
        raise SystemExit("sanitizeImportedTask KDoc not found")

    conversation_start = None
    for index, line in enumerate(lines):
        if line.startswith("internal fun sanitizeImportedConversation("):
            conversation_start = index
            break
    if conversation_start is None:
        raise SystemExit("sanitizeImportedConversation not found")
    conversation_end = None
    for index in range(conversation_start, len(lines)):
        if lines[index].rstrip("\n") == "}":
            conversation_end = index
            break
    if conversation_end is None:
        raise SystemExit("sanitizeImportedConversation closing brace not found")
    sanitize_block = "".join(lines[task_doc : conversation_end + 1])

    # 2. The nested enum, byte-for-byte (original indentation), wrapped in its class.
    enum_start = None
    for index, line in enumerate(lines):
        if line.startswith("    enum class ImportStrategy"):
            enum_start = index
            break
    if enum_start is None:
        raise SystemExit("ImportStrategy enum not found")
    enum_end = None
    for index in range(enum_start, len(lines)):
        if lines[index].rstrip("\n") == "    }":
            enum_end = index
            break
    if enum_end is None:
        raise SystemExit("ImportStrategy closing brace not found")
    enum_block = "".join(lines[enum_start : enum_end + 1])

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8", newline="") as handle:
        handle.write(HEADER)
        handle.write(sanitize_block)
        handle.write("\n/** The import strategy enum nested in DataImporter (see DataImporter.kt). */\n")
        handle.write("class DataImporter {\n")
        handle.write(enum_block)
        handle.write("}\n")
    print("extracted sanitize helpers + ImportStrategy")


if __name__ == "__main__":
    main()
