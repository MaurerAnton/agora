#!/usr/bin/env python3
"""Extracts the Anthropic request wire models and compatibility helpers from AnthropicProvider.kt.

The validator and the trace dump consume the @Serializable request models (and the two thought-
signature compatibility helpers) that live in the provider file, which cannot be compiled
standalone (Android-only imports: HTTP client, coroutines, DebugLog). The golden stand runs the
REAL declarations: this script copies the exact source regions verbatim into a generated file.
The only transformation is widening the two helpers' visibility from `private fun` to
`internal fun` so the trace dump can call them; their bodies are untouched.

Usage: python3 extract_request_models.py <AnthropicProvider.kt> <out.kt>
"""
import re
import sys

START_CLASS = "internal data class AnthropicRequest("
END_CLASS = "internal data class AnthropicUsage("
EXPECTED_CLASSES = [
    "AnthropicRequest",
    "AnthropicCacheControl",
    "AnthropicTool",
    "AnthropicThinking",
    "AnthropicOutputConfig",
    "AnthropicMessage",
    "AnthropicContentPart",
    "AnthropicImageSource",
    "AnthropicUsage",
]
START_HELPER = "private fun MessageSegment.signatureIsCompatibleWithAnthropic("
SECOND_HELPER = "private fun ChatMessage.isAnthropicToolRoundCompatible("

HEADER = """\
// GENERATED by extract_request_models.py from AnthropicProvider.kt -- do not edit.
//
// The request wire model declarations and the thought-signature compatibility helpers are copied
// verbatim from the provider file, which cannot be compiled standalone (Android-only imports); the
// validator and the request golden stand pin them here. The helpers' visibility is widened from
// private to internal so the stand driver can call them; bodies are unchanged.
package com.newoether.agora.api.anthropic

import com.newoether.agora.model.ChatMessage
import com.newoether.agora.model.MessageSegment
import com.newoether.agora.model.ModelId
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject

"""


def extract_models(lines):
    start = None
    for i, line in enumerate(lines):
        if START_CLASS in line:
            if i == 0 or lines[i - 1].strip() != "@Serializable":
                raise SystemExit(f"error: no @Serializable directly above {START_CLASS}")
            start = i - 1
            break
    if start is None:
        raise SystemExit(f"error: {START_CLASS} not found")

    end = None
    for i in range(start, len(lines)):
        if END_CLASS in lines[i]:
            for j in range(i, len(lines)):
                if lines[j].strip() == ")":
                    end = j
                    break
            break
    if end is None:
        raise SystemExit(f"error: closing paren of {END_CLASS} not found")

    region = lines[start : end + 1]
    text = "\n".join(region)
    for cls in EXPECTED_CLASSES:
        if f"internal data class {cls}(" not in text:
            raise SystemExit(f"error: {cls} is not inside the extracted model region")
    return region


def extract_function(lines, marker):
    """Finds the `private fun ...(` line for marker and takes it through brace matching."""
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")

    depth = 0
    seen_open = False
    end = None
    for i in range(start, len(lines)):
        for char in lines[i]:
            if char == "{":
                depth += 1
                seen_open = True
            elif char == "}":
                depth -= 1
        if seen_open and depth == 0:
            end = i
            break
    if end is None:
        raise SystemExit(f"error: end of {marker} not found")

    region = lines[start : end + 1]
    widened = []
    for line in region:
        if line.startswith("private fun "):
            line = "internal fun " + line[len("private fun "):]
        widened.append(line)
    return widened


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_request_models.py <AnthropicProvider.kt> <out.kt>", file=sys.stderr)
        return 2
    source_path, out_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().split("\n")

    models = extract_models(lines)
    helpers = []
    helpers += extract_function(lines, START_HELPER)
    helpers.append("")
    helpers += extract_function(lines, SECOND_HELPER)

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(HEADER + "\n".join(models) + "\n\n" + "\n".join(helpers) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
