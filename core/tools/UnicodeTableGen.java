import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;

/**
 * Emits core/src/unicode_tables.generated.hpp from the JVM's own Unicode tables.
 *
 * The Kotlin implementation runs on the JVM in tests and on Android's ICU on devices; this port
 * pins the classification to the JVM's tables, which is the runtime every parity test compares
 * against. Codepoints assigned after the device's ICU version may classify differently there;
 * counting only ever overcounts when a character looks like a letter it is not.
 *
 * Usage: java UnicodeTableGen <output.hpp>
 *
 * Flag bits, one byte per codepoint:
 *   bit0 L  \p{L}                                  (Lu Ll Lt Lm Lo)
 *   bit1 N  \p{N}                                  (Nd Nl No)
 *   bit2 A  [\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]        the o200k pattern's first letter class
 *   bit3 B  [\p{Ll}\p{Lm}\p{Lo}\p{M}]              the o200k pattern's second letter class
 *   bit4 WS the o200k pattern's explicit whitespace class
 *   bit5 JW Character.isWhitespace (the heuristic fallback's notion)
 *   bit6 JS Character.isSpaceChar
 */
public final class UnicodeTableGen {

    private static final int L = 1;
    private static final int N = 2;
    private static final int A = 4;
    private static final int B = 8;
    private static final int WS = 16;
    private static final int JW = 32;
    private static final int JS = 64;

    public static void main(String[] args) throws Exception {
        if (args.length != 1) {
            System.err.println("usage: UnicodeTableGen <output.hpp>");
            System.exit(2);
        }

        final int maxCp = 0x110000;
        byte[] flags = new byte[maxCp];
        for (int cp = 0; cp < maxCp; cp++) {
            flags[cp] = (byte) flagsOf(cp);
        }

        // Two-level table: every 256-codepoint page deduplicated by content.
        final int pages = maxCp / 256;
        short[] pageIndex = new short[pages];
        byte[][] unique = new byte[pages][];
        int uniqueCount = 0;
        for (int page = 0; page < pages; page++) {
            byte[] chunk = new byte[256];
            System.arraycopy(flags, page * 256, chunk, 0, 256);
            int found = -1;
            for (int i = 0; i < uniqueCount; i++) {
                if (java.util.Arrays.equals(unique[i], chunk)) {
                    found = i;
                    break;
                }
            }
            if (found < 0) {
                unique[uniqueCount] = chunk;
                found = uniqueCount++;
            }
            if (found > 0xFFFF) throw new IllegalStateException("page index overflow");
            pageIndex[page] = (short) found;
        }

        try (PrintWriter out = new PrintWriter(args[0], StandardCharsets.UTF_8)) {
            out.println("// Generated by core/tools/UnicodeTableGen.java. Do not edit by hand.");
            out.println("// Regenerate: javac -d /tmp core/tools/UnicodeTableGen.java && java -cp /tmp UnicodeTableGen core/src/unicode_tables.generated.hpp");
            out.println("#pragma once");
            out.println("#include <cstdint>");
            out.println();
            out.println("namespace agora::core::unicode {");
            out.println();
            out.printf("inline constexpr int kUniquePageCount = %d;%n", uniqueCount);
            out.println();
            out.println("inline constexpr std::uint8_t kPages[] = {");
            for (int i = 0; i < uniqueCount; i++) {
                out.printf("    // page %d%n    ", i);
                for (int j = 0; j < 256; j++) {
                    out.printf("%d,", unique[i][j] & 0xFF);
                    if (j % 32 == 31) {
                        if (j != 255) out.print("\n    ");
                    } else if (j % 16 == 15) {
                        out.print(' ');
                    }
                }
                out.println();
            }
            out.println("};");
            out.println();
            out.printf("inline constexpr std::uint16_t kPageIndex[%d] = {", pages);
            for (int page = 0; page < pages; page++) {
                if (page % 32 == 0) out.print("\n    ");
                out.printf("%d,", pageIndex[page] & 0xFFFF);
            }
            out.println("\n};");
            out.println();
            out.println("}  // namespace agora::core::unicode");

            // Sanity report to stderr for the caller.
            int letters = 0;
            int numbers = 0;
            int wsCount = 0;
            for (int cp = 0; cp < maxCp; cp++) {
                if ((flags[cp] & L) != 0) letters++;
                if ((flags[cp] & N) != 0) numbers++;
                if ((flags[cp] & WS) != 0) wsCount++;
            }
            System.err.printf(
                "pages=%d total, %d unique, L=%d, N=%d, WS=%d (assigned in this JVM's Unicode)%n",
                pages, uniqueCount, letters, numbers, wsCount);
        }
    }

    private static int flagsOf(int cp) {
        int type = Character.getType(cp);
        int f = 0;
        boolean upper = type == Character.UPPERCASE_LETTER;
        boolean lower = type == Character.LOWERCASE_LETTER;
        boolean title = type == Character.TITLECASE_LETTER;
        boolean modif = type == Character.MODIFIER_LETTER;
        boolean other = type == Character.OTHER_LETTER;
        boolean mark = type == Character.NON_SPACING_MARK
            || type == Character.ENCLOSING_MARK
            || type == Character.COMBINING_SPACING_MARK;
        if (upper || lower || title || modif || other) f |= L;
        if (type == Character.DECIMAL_DIGIT_NUMBER
            || type == Character.LETTER_NUMBER
            || type == Character.OTHER_NUMBER) f |= N;
        if (upper || title || modif || other || mark) f |= A;
        if (lower || modif || other || mark) f |= B;
        if (isO200kWhitespace(cp)) f |= WS;
        if (Character.isWhitespace(cp)) f |= JW;
        if (Character.isSpaceChar(cp)) f |= JS;
        return f;
    }

    /** The whitespace class exactly as spelled in BpeTokenCount.O200K_PATTERN. */
    private static boolean isO200kWhitespace(int cp) {
        switch (cp) {
            case 0x09: case 0x0A: case 0x0B: case 0x0C: case 0x0D: case 0x20:
            case 0x85: case 0xA0: case 0x1680:
            case 0x2028: case 0x2029: case 0x202F: case 0x205F: case 0x3000:
                return true;
            default:
                return cp >= 0x2000 && cp <= 0x200A;
        }
    }
}
