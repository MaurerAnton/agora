#!/usr/bin/env python3
"""Extracts the maxWaitMs helper of ShellDurableJobExecutor.kt.

The definitions builder embeds `ShellDurableJobExecutor.maxWaitMs(ctx)` in one tool description,
and the executor itself is a 500-line transport-coupled object. This copies the pure helper and
its two constants verbatim, lifting them into a stand-alone `ShellDurableJobExecutor` object so
the real ShellToolDefinitions.build() compiles against it.

Usage: python3 extract_wait_job.py <ShellDurableJobExecutor.kt> <out.kt>
"""
import sys

REGIONS = [
    ("        private const val MIN_WAIT_JOB_MS", 8, True),
    ("        private const val WAIT_JOB_OUTER_MARGIN_MS", 8, True),
    ("        internal fun maxWaitMs(ctx: GenerationContext): Int =", 8, False),
]

HEADER = """\
// GENERATED by extract_wait_job.py from ShellDurableJobExecutor.kt -- do not edit.
//
// maxWaitMs and its two constants are copied verbatim; only the member indentation is removed so
// ShellToolDefinitions.kt (which embeds the value in a tool description) compiles unchanged.
package com.newoether.agora.tool

import com.newoether.agora.viewmodel.GenerationContext

object ShellDurableJobExecutor {

"""


def extract_region(lines, marker, indent, widen):
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")

    end = None
    for i in range(start, len(lines)):
        stripped = lines[i].rstrip()
        if stripped.endswith(("=", ",")) and not stripped.endswith(("==", "<=", ">=", "!=")):
            continue
        next_line = lines[i + 1].lstrip() if i + 1 < len(lines) else ""
        if next_line.startswith(("?", "+", ".", "-")):
            continue
        end = i
        break
    if end is None:
        raise SystemExit(f"error: end of {marker} not found")

    prefix = " " * indent
    region = []
    for line in lines[start : end + 1]:
        if line.startswith(prefix):
            line = line[indent:]
        if widen and line.startswith("private const val "):
            line = "internal const val " + line[len("private const val "):]
        region.append(line)
    return region


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_wait_job.py <ShellDurableJobExecutor.kt> <out.kt>", file=sys.stderr)
        return 2
    lines = open(sys.argv[1], encoding="utf-8").read().split("\n")
    blocks = ["\n".join(extract_region(lines, marker, indent, widen))
              for marker, indent, widen in REGIONS]
    text = "\n\n".join(blocks)
    for name in ("MIN_WAIT_JOB_MS", "WAIT_JOB_OUTER_MARGIN_MS", "maxWaitMs"):
        if name not in text:
            raise SystemExit(f"error: {name} missing from the extracted region")
    with open(sys.argv[2], "w", encoding="utf-8") as handle:
        handle.write(HEADER + text + "\n}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())