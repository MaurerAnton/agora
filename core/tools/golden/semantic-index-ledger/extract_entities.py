#!/usr/bin/env python3
"""Lifts EmbeddingEntity out of data/local/ChatEntities.kt.

The ledger file itself compiles verbatim; it only needs the embedding table row type that lives in
the shared entity file. The class is copied byte for byte (annotations included) and the Room
annotations are satisfied by the stand-local stubs.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
APP = os.path.join(ROOT, "app", "src", "main", "java", "com", "newoether", "agora")
OUT = os.path.join(HERE, "build")

HEADER = """\
// GENERATED by extract_entities.py from data/local/ChatEntities.kt -- do not edit.
//
// EmbeddingEntity is copied verbatim; the Room annotations are satisfied by the stand-local stubs
// (Room is a persistence framework: the annotations have no runtime behaviour the ledger observes).
package com.newoether.agora.data.local

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

"""


def extract(text: str, name: str) -> str:
    lines = text.split("\n")
    declaration = "data class %s(" % name
    try:
        start = next(i for i, line in enumerate(lines) if line.startswith(declaration))
    except StopIteration:
        raise SystemExit("error: %s not found" % name)

    # Include the annotation block directly above the declaration.
    annotation_start = start
    probe = start - 1
    while probe >= 0:
        stripped = lines[probe].strip()
        if stripped == "":
            break
        if lines[probe].startswith("@"):
            annotation_start = probe
            probe -= 1
            continue
        if lines[probe].startswith("    ") or stripped in (")", "],"):
            annotation_start = probe
            probe -= 1
            continue
        break

    end = None
    for index in range(start, len(lines)):
        if lines[index] == "}":
            end = index
            break
    if end is None:
        raise SystemExit("error: end of %s not found" % name)
    return "\n".join(lines[annotation_start:end + 1])


def main() -> int:
    os.makedirs(OUT, exist_ok=True)
    entities = open(os.path.join(APP, "data", "local", "ChatEntities.kt"), encoding="utf-8").read()
    lifted = extract(entities, "EmbeddingEntity")
    with open(os.path.join(OUT, "EmbeddingEntity.kt"), "w", encoding="utf-8") as handle:
        handle.write(HEADER + lifted + "\n")
    print("Extracted EmbeddingEntity")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
