#!/usr/bin/env python3
"""Lifts the message clone policy out of the app tree.

Two pieces are needed and neither compiles on its own:

* `data/local/ChatEntities.kt` — the Room entity `MessageEntity` lives in a file that also
  declares the DAOs and the other tables, so the class is copied out here (byte for byte,
  annotations included) and the Room annotations are satisfied by the stand-local stubs.
* `data/MessageAttachmentCloneSession.kt` — the policy itself; only its `internal` visibility is
  widened so the driver can call it.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
APP = os.path.join(ROOT, "app", "src", "main", "java", "com", "newoether", "agora")
OUT = os.path.join(HERE, "build")

ENTITY_HEADER = """\
// GENERATED by extract_clone_policy.py from data/local/ChatEntities.kt -- do not edit.
//
// MessageEntity is copied verbatim; the Room annotations are satisfied by the stand-local stubs
// (Room is a persistence framework: the annotations have no runtime behaviour the clone policy
// can observe).
package com.newoether.agora.data.local

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import com.newoether.agora.model.MessageSource
import com.newoether.agora.model.MessageStatus
import com.newoether.agora.model.Participant

"""


def widen(text: str) -> str:
    out = []
    for line in text.split("\n"):
        stripped = line.lstrip()
        if stripped.startswith("internal "):
            indent = line[: len(line) - len(stripped)]
            line = indent + stripped[len("internal "):]
        out.append(line)
    return "\n".join(out)


def extract_class(text: str, name: str) -> str:
    lines = text.split("\n")
    start = None
    for index, line in enumerate(lines):
        if line.startswith("@Entity") or line.startswith("data class %s(" % name):
            if line.startswith("data class %s(" % name):
                start = index
                break
    if start is None:
        raise SystemExit("error: %s not found" % name)
    # walk back over the annotation block
    while start > 0 and (lines[start - 1].startswith("@") or lines[start - 1].startswith(" " * 8)
                         or lines[start - 1].strip() == ""):
        if lines[start - 1].strip() == "":
            break
        start -= 1
    end = None
    for index in range(start, len(lines)):
        if lines[index] == "}":
            end = index
            break
    if end is None:
        raise SystemExit("error: end of %s not found" % name)
    return "\n".join(lines[start:end + 1])


def main() -> int:
    os.makedirs(OUT, exist_ok=True)

    entities = open(os.path.join(APP, "data", "local", "ChatEntities.kt"), encoding="utf-8").read()
    message_entity = extract_class(entities, "MessageEntity")
    with open(os.path.join(OUT, "MessageEntity.kt"), "w", encoding="utf-8") as handle:
        handle.write(ENTITY_HEADER + message_entity + "\n")

    policy_path = os.path.join(APP, "data", "MessageAttachmentCloneSession.kt")
    if not os.path.exists(policy_path):
        print("error: missing %s" % policy_path, file=sys.stderr)
        return 2
    policy = open(policy_path, encoding="utf-8").read()
    with open(os.path.join(OUT, "MessageAttachmentCloneSession.kt"), "w", encoding="utf-8") as handle:
        handle.write(widen(policy))
    print("Extracted MessageEntity and the clone policy")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
