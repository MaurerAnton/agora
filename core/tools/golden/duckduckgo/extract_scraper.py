#!/usr/bin/env python3
"""Extracts the parsing/scrubbing pieces of DuckDuckGoScraper.kt.

The scraper file cannot be compiled standalone (it wires OkHttp through HttpClient), but the
golden stand runs the REAL parsing logic: this script copies the exact source regions verbatim
into a generated file. Class members are lifted to file level (the member indentation is
removed) and `private` visibility is widened to `internal` so the trace dump can call them;
bodies, regex literals and constants are untouched.

Usage: python3 extract_scraper.py <DuckDuckGoScraper.kt> <out.kt>
"""
import sys

# (marker, expected indentation to strip, widen "private" declarations)
REGIONS = [
    ("    data class WebResult(", 4, False),
    ("        private const val DEFAULT_MAX_RESULTS", 8, True),
    ("        private const val PAGE_SIZE", 8, True),
    ("        private const val MAX_PAGES", 8, True),
    ('        private val LINK_TAG_REGEX', 8, True),
    ('        private val LINK_TEXT_REGEX', 8, True),
    ('        private val HREF_REGEX', 8, True),
    ('        private val SNIPPET_REGEX', 8, True),
    ('        private val UDDG_REGEX', 8, True),
    ('        private val HTML_TAG_REGEX', 8, True),
    ('        private val CAPTCHA_REGEX', 8, True),
    ('        private val VQD_REGEX', 8, True),
    ('        private val OFFSET_REGEX', 8, True),
    ("    internal fun parseResults(", 4, False),
    ("    private fun extractUrl(", 4, True),
    ("    private fun String.stripHtml()", 4, True),
]

HEADER = """\
// GENERATED by extract_scraper.py from DuckDuckGoScraper.kt -- do not edit.
//
// The result model, the parsing regexes, parseResults, extractUrl and stripHtml are copied
// verbatim from the scraper file (which wires OkHttp and cannot compile standalone); the member
// bodies are lifted to file level and visibility is widened private -> internal. The search
// loop itself is transcribed by the stand driver over these real pieces.
package com.newoether.agora.api

import java.net.URLDecoder

"""


def extract_region(lines, marker, indent, widen):
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")

    # Single-line declarations (const/val or expression bodies) end on their own line when the
    # parentheses balance and no continuation line follows; otherwise scan with brace/paren
    # matching and continuation lookahead.
    paren = 0
    brace = 0
    seen_brace = False
    end = None
    for i in range(start, len(lines)):
        for char in lines[i]:
            if char == "{":
                brace += 1
                seen_brace = True
            elif char == "}":
                brace -= 1
            elif char in "([":
                paren += 1
            elif char in ")]":
                paren -= 1
        if seen_brace:
            if brace == 0:
                end = i
                break
            continue
        if paren != 0:
            continue
        stripped = lines[i].rstrip()
        if stripped.endswith(("=", ",", "&&", "||", "+", "->")):
            continue
        next_stripped = lines[i + 1].lstrip() if i + 1 < len(lines) else ""
        if next_stripped.startswith(("?:", "?.", "&&", "||", "+", ".")):
            continue
        end = i
        break
    if end is None:
        raise SystemExit(f"error: end of {marker} not found")

    prefix = " " * indent
    region = []
    for line in lines[start : end + 1]:
        if line.startswith(prefix):
            line = line[indent:]
        if widen:
            if line.startswith("private fun "):
                line = "internal fun " + line[len("private fun "):]
            elif line.startswith("private val "):
                line = "internal val " + line[len("private val "):]
            elif line.startswith("private const val "):
                line = "internal const val " + line[len("private const val "):]
        region.append(line)
    return region


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_scraper.py <DuckDuckGoScraper.kt> <out.kt>", file=sys.stderr)
        return 2
    source_path, out_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().split("\n")

    blocks = []
    for marker, indent, widen in REGIONS:
        blocks.append("\n".join(extract_region(lines, marker, indent, widen)))

    text = "\n\n".join(blocks)
    for name in ("WebResult", "parseResults", "extractUrl", "stripHtml", "CAPTCHA_REGEX",
                 "VQD_REGEX", "OFFSET_REGEX", "DEFAULT_MAX_RESULTS", "PAGE_SIZE", "MAX_PAGES"):
        if name not in text:
            raise SystemExit(f"error: {name} missing from the extracted region")

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(HEADER + text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
