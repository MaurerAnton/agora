#!/usr/bin/env python3
"""Extracts the Gemini request-side helpers from GeminiProvider.kt.

The provider file cannot be compiled standalone (HTTP client, coroutines, DebugLog), but the
request golden stand runs the REAL helpers: this script copies the exact source regions verbatim
into a generated file. The only transformation is widening `private fun JsonObject.stringContent`
to `internal fun` so the trace dump can call it; bodies are untouched.

Usage: python3 extract_gemini_helpers.py <GeminiProvider.kt> <out.kt>
"""
import sys

MARKERS = [
    "internal fun ChatMessage.isGeminiToolRoundCompatible(",
    "private fun JsonObject.stringContent(",
    "internal fun geminiModelMessageParts(",
]
EXPECTED = [
    "isGeminiToolRoundCompatible",
    "stringContent",
    "geminiModelMessageParts",
]

HEADER = """\
// GENERATED by extract_gemini_helpers.py from GeminiProvider.kt -- do not edit.
//
// The request-side helpers are copied verbatim from the provider file, which cannot be compiled
// standalone (Android-only imports); the request golden stand pins them here. The only change is
// widening `private fun JsonObject.stringContent` to `internal fun`.
package com.newoether.agora.api.gemini

import com.newoether.agora.model.ChatMessage
import com.newoether.agora.model.MessageSegment
import com.newoether.agora.model.ModelId
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

"""


def extract_function(lines, marker):
    """Finds the function declaration line for marker and takes it through the function end.

    Unified end detection: once a brace has been opened, the function ends when braces balance;
    before that (single-expression bodies without any brace) it ends when the parentheses balance
    at a line end.
    """
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")

    paren = 0
    brace = 0
    seen_brace = False
    end = None
    for i in range(start, len(lines)):
        for char in lines[i]:
            if char == "{":
                brace += 1
                seen_brace = True
            elif char == "}":
                brace -= 1
            elif char in "([":
                paren += 1
            elif char in ")]":
                paren -= 1
        if seen_brace:
            if brace == 0:
                end = i
                break
        elif paren == 0:
            stripped = lines[i].rstrip()
            if stripped.endswith(("=", ",", "&&", "||", "+", "->")):
                continue  # the expression continues on the next line
            end = i
            break
    if end is None:
        raise SystemExit(f"error: end of {marker} not found")

    region = lines[start : end + 1]
    widened = []
    for line in region:
        if line.startswith("private fun "):
            line = "internal fun " + line[len("private fun "):]
        widened.append(line)
    return widened


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_gemini_helpers.py <GeminiProvider.kt> <out.kt>", file=sys.stderr)
        return 2
    source_path, out_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().split("\n")

    blocks = []
    for marker in MARKERS:
        blocks.append("\n".join(extract_function(lines, marker)))

    text = "\n\n".join(blocks)
    for name in EXPECTED:
        if name not in text:
            raise SystemExit(f"error: {name} missing from the extracted region")

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(HEADER + text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
