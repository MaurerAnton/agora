#!/usr/bin/env python3
"""Lift DataImporter.sanitizeImportedLoop into the DataExporter stand.

DataExporter.kt calls the top-level `internal fun sanitizeImportedLoop(loop: LoopEntity)` that
lives in DataImporter.kt. Compiling DataImporter.kt would drag in the whole import composition
root (ChatDatabase, semantic-model repair, transfer coordinator) that the export path never
touches. This extractor copies the function's source text byte-for-byte and adds only the package
line plus the two imports the function itself uses. The output is generated into build/ so the
app file stays the single source of truth.
"""
from __future__ import annotations

import os
import sys

HEADER = """// Generated by extract_sanitize_imported_loop.py from app/src/main/java/com/newoether/agora/data/DataImporter.kt.
// The function body below is copied byte-for-byte from DataImporter.kt; only the package and the
// two imports it needs are added here.
package com.newoether.agora.data

import com.newoether.agora.automation.LoopPolicy
import com.newoether.agora.data.local.LoopEntity

"""


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: extract_sanitize_imported_loop.py <DataImporter.kt> <output.kt>")
    source_path, output_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().splitlines(keepends=True)

    start = None
    for index, line in enumerate(lines):
        if line.startswith("internal fun sanitizeImportedLoop("):
            start = index
            break
    if start is None:
        raise SystemExit("sanitizeImportedLoop not found in " + source_path)

    end = None
    for index in range(start, len(lines)):
        if lines[index].rstrip("\n") == "}":
            end = index
            break
    if end is None:
        raise SystemExit("sanitizeImportedLoop closing brace not found")

    body = "".join(lines[start : end + 1])
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8", newline="") as handle:
        handle.write(HEADER)
        handle.write(body)


if __name__ == "__main__":
    main()
