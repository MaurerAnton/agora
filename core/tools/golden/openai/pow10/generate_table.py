#!/usr/bin/env python3
"""Rebuilds core/src/jvm_pow10_table.generated.hpp from pow10_jvm.txt.

The table pins Math.pow(10.0, e) bit patterns for integer exponents e in
[-400, 400]. std::pow differs from the desktop JVM by one ulp for some
exponents, and the golden traces were frozen on the JVM, so the exponent
path of consumeNumericLiteral must use the JVM bits to stay identical on
every host libm.

Regenerate:
    kotlinc ProbePow10.kt -include-runtime -d probe.jar && \
        java -jar probe.jar > pow10_jvm.txt
    python3 generate_table.py
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUTPUT = HERE.parents[3] / "src" / "jvm_pow10_table.generated.hpp"


def main() -> None:
    tokens = (HERE / "pow10_jvm.txt").read_text().split()
    assert len(tokens) % 2 == 0, "expected '<exponent> <hex bits>' pairs"
    entries = [
        (int(tokens[i]), int(tokens[i + 1], 16)) for i in range(0, len(tokens), 2)
    ]
    assert entries[0][0] == -400 and entries[-1][0] == 400 and len(entries) == 801

    lines = [
        "// Generated by core/tools/golden/openai/pow10/generate_table.py from the JDK.",
        "// Bit patterns of Math.pow(10.0, e) for integer e in [-400, 400], index e + 400.",
        "// Embedded so the exponent path of consumeNumericLiteral stays bit-identical to the",
        "// desktop JVM that froze the golden traces, independent of the host libm.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace agora::core::openai {",
        "",
        "inline constexpr std::uint64_t kJvmPow10Bits[801] = {",
    ]
    for exponent, bits in entries:
        lines.append("    0x%016xULL,  // e = %d" % (bits, exponent))
    lines += ["};", "", "}  // namespace agora::core::openai", ""]
    OUTPUT.write_text("\n".join(lines))
    print("wrote", OUTPUT, "with", len(entries), "entries")


if __name__ == "__main__":
    main()
