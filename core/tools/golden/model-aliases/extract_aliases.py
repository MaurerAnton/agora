#!/usr/bin/env python3
"""Extracts the model-alias inference block from CustomProviderIdentity.kt.

The file also owns provider-id normalization and conversation display helpers, but the alias block
(alias regexes, the display-name tables and inferModelAlias with its Gemini/Claude/Nova branches)
is a self-contained top-level region with no Android or viewmodel dependencies. This copies it
verbatim; only `private` visibility is widened so the trace dump can call the helpers.

Usage: python3 extract_aliases.py <CustomProviderIdentity.kt> <out.kt>
"""
import sys

START = "private val aliasSeparators"
END_MARKER = "private fun isValidSnapshotDate"

HEADER = """\
// GENERATED by extract_aliases.py from CustomProviderIdentity.kt -- do not edit.
//
// The alias inference block (patterns, display-name tables, inferModelAlias and its Gemini /
// Claude / Nova branches) is copied verbatim; only `private` is widened to `internal`.
package com.newoether.agora.data

import java.time.LocalDate
import java.time.format.DateTimeFormatter
import java.util.Locale

"""


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_aliases.py <CustomProviderIdentity.kt> <out.kt>", file=sys.stderr)
        return 2
    lines = open(sys.argv[1], encoding="utf-8").read().split("\n")

    start = None
    for i, line in enumerate(lines):
        if line.startswith(START):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {START} not found")

    marker_index = None
    for i in range(start, len(lines)):
        if lines[i].startswith(END_MARKER):
            marker_index = i
            break
    if marker_index is None:
        raise SystemExit(f"error: {END_MARKER} not found")

    # The region ends at the next top-level declaration: isValidSnapshotDate uses an expression
    # body whose brace closes inline, so there is no standalone "}" to stop at.
    end = len(lines) - 1
    for i in range(marker_index + 1, len(lines)):
        if lines[i].startswith(("fun ", "private fun ", "internal fun ", "private val ",
                                "internal val ", "private const val ", "@")):
            end = i - 1
            break

    region = []
    for line in lines[start : end + 1]:
        if line.startswith("private val "):
            line = "internal val " + line[len("private val "):]
        elif line.startswith("private fun "):
            line = "internal fun " + line[len("private fun "):]
        region.append(line)

    text = "\n".join(region)
    for name in ("inferModelAlias", "formatAliasToken", "humanizeModelAlias", "aliasSeparators",
                 "claudeFamilyFirstAliasPattern", "exactAliasTokenDisplayNames",
                 "isValidSnapshotDate"):
        if name not in text:
            raise SystemExit(f"error: {name} missing from the extracted region")

    with open(sys.argv[2], "w", encoding="utf-8") as handle:
        handle.write(HEADER + text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())