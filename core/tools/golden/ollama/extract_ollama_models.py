#!/usr/bin/env python3
"""Extracts the Ollama wire models and loop helpers from OllamaProvider.kt.

The provider file cannot be compiled standalone (HTTP client, coroutines, DebugLog), but the
golden stand runs the REAL declarations: this script copies the exact source regions verbatim
into a generated file (the models OllamaChatRequest..OllamaStreamResponse, plus
ollamaStreamTermination and OllamaStreamResponse.toTokenUsage).

Usage: python3 extract_ollama_models.py <OllamaProvider.kt> <out.kt>
"""
import sys

START_CLASS = "internal data class OllamaChatRequest("
END_CLASS = "internal data class OllamaStreamResponse("
EXPECTED = [
    "OllamaChatRequest",
    "OllamaMessage",
    "OllamaStreamResponse",
]
FUNCTION_MARKERS = [
    "internal fun ollamaStreamTermination(",
    "internal fun OllamaStreamResponse.toTokenUsage(): TokenUsage {",
]

HEADER = """\
// GENERATED by extract_ollama_models.py from OllamaProvider.kt -- do not edit.
//
// The wire models and the loop helpers are copied verbatim from the provider file, which cannot
// be compiled standalone (Android-only imports); the request/stream golden stand pins them here.
package com.newoether.agora.api.ollama

import com.newoether.agora.api.GenerationError
import com.newoether.agora.api.OpenAiToolCall
import com.newoether.agora.api.ToolDefinition
import com.newoether.agora.api.util.StreamTermination
import com.newoether.agora.model.TokenUsage
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject

"""


def extract_models(lines):
    start = None
    for i, line in enumerate(lines):
        if START_CLASS in line:
            if i == 0 or lines[i - 1].strip() != "@Serializable":
                raise SystemExit(f"error: no @Serializable directly above {START_CLASS}")
            start = i - 1
            break
    if start is None:
        raise SystemExit(f"error: {START_CLASS} not found")

    end = None
    for i in range(start, len(lines)):
        if END_CLASS in lines[i]:
            for j in range(i, len(lines)):
                if lines[j].strip() == ")":
                    end = j
                    break
            break
    if end is None:
        raise SystemExit(f"error: closing paren of {END_CLASS} not found")

    region = lines[start : end + 1]
    text = "\n".join(region)
    for cls in EXPECTED:
        if f"internal data class {cls}(" not in text:
            raise SystemExit(f"error: {cls} is not inside the extracted model region")
    return region


def extract_function(lines, marker):
    """Unified end detection: braces balance after the first '{', expression bodies end when the
    parentheses balance at a line end that starts no continuation."""
    start = None
    for i, line in enumerate(lines):
        if line.startswith(marker):
            start = i
            break
    if start is None:
        raise SystemExit(f"error: {marker} not found")

    paren = 0
    brace = 0
    seen_brace = False
    end = None
    for i in range(start, len(lines)):
        for char in lines[i]:
            if char == "{":
                brace += 1
                seen_brace = True
            elif char == "}":
                brace -= 1
            elif char in "([":
                paren += 1
            elif char in ")]":
                paren -= 1
        if seen_brace:
            if brace == 0:
                end = i
                break
            continue
        if paren != 0:
            continue
        stripped = lines[i].rstrip()
        if stripped.endswith(("=", ",", "&&", "||", "+", "->")):
            continue
        next_stripped = lines[i + 1].lstrip() if i + 1 < len(lines) else ""
        if next_stripped.startswith(("?:", "?.", "&&", "||", "+", ".")):
            continue
        end = i
        break
    if end is None:
        raise SystemExit(f"error: end of {marker} not found")
    return lines[start : end + 1]


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_ollama_models.py <OllamaProvider.kt> <out.kt>", file=sys.stderr)
        return 2
    source_path, out_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().split("\n")

    blocks = ["\n".join(extract_models(lines))]
    for marker in FUNCTION_MARKERS:
        blocks.append("\n".join(extract_function(lines, marker)))

    text = "\n\n".join(blocks)
    for cls in EXPECTED + ["ollamaStreamTermination", "toTokenUsage"]:
        if cls not in text:
            raise SystemExit(f"error: {cls} missing from the extracted region")

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(HEADER + text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
