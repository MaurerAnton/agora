#!/usr/bin/env python3
"""Extracts the transport-neutral HTTP policy declarations from HttpClient.kt.

HttpClient.kt is a 608-line OkHttp/Android transport object. The golden stand pins the
policy that can be decided without a socket: host locality, the cleartext credential
guard, proxy sanitisation, bypass matching, CIDR matching and proxy authorization.

The declarations below are copied verbatim out of `object HttpClient`; the only edits
are the visibility of the private helpers (`private` -> `internal`, so the driver can
call them) and the four-space dedent that moves them to file scope. The extractor also
asserts that the source snippets the small derived wrappers rely on are still present,
so a shape change in HttpClient.kt fails loudly instead of silently drifting.

Usage: python3 extract_policy.py <HttpClient.kt> <out.kt>
"""
import os
import sys

HEADER = """\
// GENERATED by extract_policy.py -- do not edit.
//
// Pure policy declarations copied verbatim from api/HttpClient.kt. The private helpers were
// widened to internal so the golden driver can call them; every declaration was dedented out
// of `object HttpClient` by four spaces. The derived wrappers at the bottom parameterise the
// stored `proxyConfig` field and are checked against their source snippets by the extractor.
package com.newoether.agora.api

import java.io.IOException

"""

# The derived wrappers below are only faithful while these source lines exist.
REQUIRED_SNIPPETS = [
    "config?.takeIf { it.host.isNotBlank() && it.port in 1..65535 }",
    "if (cfg == null || cfg.username.isBlank() || cfg.type != ProxyType.HTTP) return null",
    'if (response.request.header("Proxy-Authorization") != null) return null',
    "okhttp3.Credentials.basic(cfg.username, cfg.password)",
    "val type = if (cfg.type == ProxyType.SOCKS) java.net.Proxy.Type.SOCKS else java.net.Proxy.Type.HTTP",
    "java.net.InetSocketAddress.createUnresolved(cfg.host, cfg.port)",
    ".connectTimeout(30, TimeUnit.SECONDS)",
    ".readTimeout(5, TimeUnit.MINUTES)",
    ".writeTimeout(30, TimeUnit.SECONDS)",
]

DERIVED = """\
// -- derived wrappers ---------------------------------------------------------------------------

// setProxy's takeIf (the right-hand side of the assignment), with the field as a parameter.
internal fun sanitizedProxyConfig(config: ProxyConfig?): ProxyConfig? =
    config?.takeIf { it.host.isNotBlank() && it.port in 1..65535 }

// resolveProxy with the stored proxyConfig field as a parameter. The caller passes the result of
// sanitizedProxyConfig, exactly as setProxy stores it before the selector reads it.
internal fun resolveProxy(host: String, config: ProxyConfig?): java.net.Proxy {
    val cfg = config ?: return java.net.Proxy.NO_PROXY
    if (isProxyBypassed(host, cfg.bypass)) return java.net.Proxy.NO_PROXY
    val type = if (cfg.type == ProxyType.SOCKS) java.net.Proxy.Type.SOCKS else java.net.Proxy.Type.HTTP
    return java.net.Proxy(type, java.net.InetSocketAddress.createUnresolved(cfg.host, cfg.port))
}

// proxyAuthenticator's decision plus OkHttp Credentials.basic. Credentials.basic is
// ISO-8859-1 + standard Base64; the platform substitution is documented in the stand README.
internal fun proxyAuthorizationHeader(config: ProxyConfig?, hasExistingHeader: Boolean): String? {
    if (config == null || config.username.isBlank() || config.type != ProxyType.HTTP) return null
    if (hasExistingHeader) return null
    return "Basic " + java.util.Base64.getEncoder().encodeToString(
        (config.username + ":" + config.password).toByteArray(Charsets.ISO_8859_1),
    )
}

// HttpClient.client's builder: connect 30s, read 5min, write 30s, and the OkHttp 5 defaults for
// retry/redirects (all true). The extractor checks the three timeout lines above.
internal data class ClientPolicy(
    val connectTimeoutSeconds: Long,
    val readTimeoutSeconds: Long,
    val writeTimeoutSeconds: Long,
    val retryOnConnectionFailure: Boolean,
    val followRedirects: Boolean,
    val followSslRedirects: Boolean,
)

internal fun clientPolicy(): ClientPolicy = ClientPolicy(
    connectTimeoutSeconds = 30,
    readTimeoutSeconds = 300,
    writeTimeoutSeconds = 30,
    retryOnConnectionFailure = true,
    followRedirects = true,
    followSslRedirects = true,
)
"""


def find_start(lines, marker):
    for index, line in enumerate(lines):
        if line.lstrip().startswith(marker):
            return index
    raise SystemExit(f"error: marker not found: {marker}")


def extract_function(lines, marker):
    start = find_start(lines, marker)
    depth = 0
    end = None
    for index in range(start, len(lines)):
        depth += lines[index].count("{") - lines[index].count("}")
        if index > start and depth <= 0:
            end = index
            break
    if end is None:
        raise SystemExit(f"error: closing brace not found for {marker}")
    return lines[start:end + 1]


def extract_data_class(lines, marker):
    start = find_start(lines, marker)
    for index in range(start, len(lines)):
        if lines[index].rstrip() == "    )":
            return lines[start:index + 1]
    raise SystemExit(f"error: closing parenthesis not found for {marker}")


def dedent(block):
    result = []
    for line in block:
        if line.startswith("    "):
            result.append(line[4:])
        else:
            result.append(line)
    return result


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    source_path, out_path = sys.argv[1], sys.argv[2]
    with open(source_path) as handle:
        source = handle.read()
        lines = source.splitlines(keepends=True)

    for snippet in REQUIRED_SNIPPETS:
        if snippet not in source:
            raise SystemExit(f"error: source snippet not found: {snippet}")

    blocks = []
    # CREDENTIAL_HEADERS is one line.
    index = find_start(lines, "private val CREDENTIAL_HEADERS")
    blocks.append([lines[index].replace("private val", "internal val", 1)])

    blocks.append(extract_function(lines, "internal fun isLocalHost("))
    blocks.append(extract_function(lines, "internal fun guardCleartextCredentials("))

    # ProxyType is a one-line enum.
    index = find_start(lines, "enum class ProxyType")
    blocks.append([lines[index]])

    blocks.append(extract_data_class(lines, "data class ProxyConfig("))
    blocks.append(extract_function(lines, "private fun isProxyBypassed("))
    blocks.append(extract_function(lines, "private fun ipv4ToLong("))
    blocks.append(extract_function(lines, "private fun ipv4InCidr("))

    rendered = []
    for block in blocks:
        block = dedent(block)
        block = [line.replace("private fun", "internal fun", 1) for line in block]
        rendered.append("".join(block).rstrip() + "\n")

    parent = os.path.dirname(out_path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(out_path, "w") as handle:
        handle.write(HEADER)
        handle.write("\n\n".join(rendered))
        handle.write("\n")
        handle.write(DERIVED)
    print(f"extracted {sum(len(block) for block in blocks)} lines into {out_path}")


if __name__ == "__main__":
    main()
