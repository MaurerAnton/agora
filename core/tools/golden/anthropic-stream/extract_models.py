#!/usr/bin/env python3
"""Extracts the Anthropic stream-event model classes from AnthropicProvider.kt.

The router consumes the @Serializable event models that live in the provider file, and that file
cannot be compiled standalone (it imports Android-only surfaces: DebugLog, coroutines, the HTTP
client). The golden stand still runs the REAL model declarations: this script copies the exact
source region (AnthropicStreamEvent through AnthropicUsage, verbatim) into a generated file with
the imports the classes need.

Usage: python3 extract_models.py <AnthropicProvider.kt> <out.kt>
"""
import sys

START_CLASS = "internal data class AnthropicStreamEvent("
END_CLASS = "internal data class AnthropicUsage("
EXPECTED = [
    "AnthropicStreamEvent",
    "AnthropicStreamError",
    "AnthropicDelta",
    "AnthropicContentBlock",
    "AnthropicMessageInfo",
    "AnthropicUsage",
]

HEADER = """\
// GENERATED by extract_models.py from AnthropicProvider.kt -- do not edit.
//
// The stream-event model declarations are copied verbatim from the provider file, which cannot be
// compiled standalone (Android-only imports); the router golden stand pins them here.
package com.newoether.agora.api.anthropic

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject

"""


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: extract_models.py <AnthropicProvider.kt> <out.kt>", file=sys.stderr)
        return 2
    source_path, out_path = sys.argv[1], sys.argv[2]
    lines = open(source_path, encoding="utf-8").read().split("\n")

    start = None
    for i, line in enumerate(lines):
        if START_CLASS in line:
            if i == 0 or lines[i - 1].strip() != "@Serializable":
                print(f"error: no @Serializable directly above {START_CLASS}", file=sys.stderr)
                return 1
            start = i - 1
            break
    if start is None:
        print(f"error: {START_CLASS} not found", file=sys.stderr)
        return 1

    end = None
    for i in range(start, len(lines)):
        if END_CLASS in lines[i]:
            for j in range(i, len(lines)):
                if lines[j].strip() == ")":
                    end = j
                    break
            break
    if end is None:
        print(f"error: closing paren of {END_CLASS} not found", file=sys.stderr)
        return 1

    region = "\n".join(lines[start : end + 1])
    for cls in EXPECTED:
        if f"internal data class {cls}(" not in region:
            print(f"error: {cls} is not inside the extracted region", file=sys.stderr)
            return 1

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(HEADER + region + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
