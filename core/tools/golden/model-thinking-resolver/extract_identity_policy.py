#!/usr/bin/env python3
"""Extracts the identity-policy slice used by CustomProviderConfig.kt.

CustomProviderIdentity.kt also contains Room/model migration and UUID code that cannot compile
host-side. `CustomProviderConfig.providerId` only needs `CustomProviderIdentityPolicy.isStableId`,
so this script copies the stable-id pattern, its compiled Regex and the function body out of the
real file verbatim. The surrounding object is closed at the end of the copied slice; no logic is
retyped. The provider-identity golden stand pins the full identity policy separately.
"""
import re
import sys
from pathlib import Path

WANTED = (
    '    private const val STABLE_ID_PATTERN =',
    '    private val stableIdPattern = Regex(',
    '    fun isStableId(value: String): Boolean',
)


def block(text: str, first: str, end_marker: str) -> str:
    start = text.index(first)
    end = text.index(end_marker, start)
    return text[start:end]


def main() -> int:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <CustomProviderIdentity.kt> <out.kt>", file=sys.stderr)
        return 2
    source = Path(sys.argv[1]).read_text(encoding="utf-8")
    header = source.index("internal object CustomProviderIdentityPolicy")
    body = source[header:]

    pattern = block(body, WANTED[0], "    private val stableIdInTextPattern")
    is_stable = block(body, WANTED[2], "    fun replaceStableIdsForDisplay")

    # The function uses an expression body, so the outer object close below is the only brace.
    is_stable = is_stable.rstrip()

    out = "package com.newoether.agora.data\n\n" \
          "// GENERATED by extract_identity_policy.py -- copied verbatim from\n" \
          "// app/src/main/java/com/newoether/agora/data/CustomProviderIdentity.kt.\n" \
          "internal object CustomProviderIdentityPolicy {\n" + pattern + is_stable + "\n}\n"
    Path(sys.argv[2]).parent.mkdir(parents=True, exist_ok=True)
    Path(sys.argv[2]).write_text(out, encoding="utf-8")
    print(f"extracted CustomProviderIdentityPolicy.isStableId into {sys.argv[2]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
