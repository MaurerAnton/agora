#!/usr/bin/env python3
"""Lifts the model declarations RunRecoveryPolicy.kt needs out of model/ChatMessage.kt, verbatim.

RunRecoveryPolicy.kt itself compiles unchanged from the app tree, but ChatMessage.kt cannot
compile host-side: it is annotated with androidx.compose.runtime.Immutable and its neighbours
(ChatMessage, ChatConversation, the display-mode objects) pull in Compose, Room and the whole UI
model. The policy only needs the declarations below, so this script copies them out byte for byte
instead of retyping them:

    ToolImageAttachment, StreamingTextDelta, MessageSegment,
    ToolExecutionStates, Participant, MessageStatus

ToolImageAttachment and StreamingTextDelta are MessageSegment's field types; all six blocks are
copied exactly as written (annotations, comments and bodies included). @Immutable is supplied by
the stand's stub, a compile-only Compose marker, so the generated file is not edited at all.

Fails loudly if any declaration disappears or is malformed, so the stand can never silently drift
onto a stale transcription.
"""

import re
import sys

WANTED = (
    "ToolImageAttachment",
    "StreamingTextDelta",
    "MessageSegment",
    "ToolExecutionStates",
    "Participant",
    "MessageStatus",
)

HEADER = """package com.newoether.agora.model

// GENERATED by extract_model_types.py from app/src/main/java/com/newoether/agora/model/
// ChatMessage.kt -- do not edit. The declarations below are copied verbatim.
import androidx.compose.runtime.Immutable
import kotlinx.serialization.Serializable
import kotlinx.serialization.Transient
import kotlinx.serialization.json.JsonObject

"""

DECLARATION = r"^(?:(?:data|internal data|public data) class|class|object|enum class) {}\b"
# An annotation, KDoc opener/continuation, or line comment directly above the declaration.
OWNED_BY_HEADER = re.compile(r"^(?:@|/\*\*|\*/|\*|//)")


def skip_literal(text: str, at: int) -> int:
    """Returns the index just past the string literal starting at `at`."""
    quote = text[at]
    at += 1
    while at < len(text):
        if text[at] == "\\":
            at += 2
            continue
        if text[at] == quote:
            return at + 1
        at += 1
    return at


def declaration_end(text: str, start: int, name: str) -> int:
    """Returns the index just past the declaration starting at `start`.

    A data class without a body ends at the primary constructor's closing paren, while one with a
    body (MessageSegment has isProviderHostedTool) continues through the matching brace. Scanning
    for `{` alone would run through a bodyless class into its neighbour, and stopping at the first
    top-level `)` would truncate a class body, so both are handled explicitly.
    """
    paren = 0
    brace = 0
    at = start
    while at < len(text):
        char = text[at]
        if char == '"':
            at = skip_literal(text, at)
            continue
        if text.startswith("//", at):
            newline = text.find("\n", at)
            at = len(text) if newline < 0 else newline
            continue
        if text.startswith("/*", at):
            close = text.find("*/", at + 2)
            at = len(text) if close < 0 else close + 2
            continue
        if char == "(":
            paren += 1
        elif char == ")":
            paren -= 1
            if paren == 0 and brace == 0:
                probe = at + 1
                while probe < len(text) and text[probe] in " \t\r\n":
                    probe += 1
                if probe >= len(text) or text[probe] != "{":
                    return at + 1
                # A class body follows: keep scanning so its closing brace is included.
        elif char == "{":
            brace += 1
        elif char == "}":
            brace -= 1
            if brace == 0:
                return at + 1
        at += 1
    raise SystemExit(f"error: unterminated declaration `{name}` in ChatMessage.kt")


def extract(text: str, name: str) -> str:
    """Returns `name` with its own annotations and KDoc, through its closing brace."""
    declaration = DECLARATION.format(re.escape(name))
    match = re.search(declaration, text, re.MULTILINE)
    if match is None:
        raise SystemExit(f"error: declaration `{name}` not found in ChatMessage.kt")

    # Walk back over the annotation/KDoc block that belongs to THIS declaration; stop at the
    # first line that closes something else, so neighbouring declarations are never pulled in.
    lines = text[: match.start()].split("\n")
    if lines and lines[-1] == "":
        lines.pop()  # the newline that terminates the last preceding line
    owned = 0
    while lines:
        candidate = lines[-1]
        if not (OWNED_BY_HEADER.match(candidate.strip()) or candidate.lstrip().startswith("*")):
            break
        owned += 1
        lines.pop()

    start = match.start()
    for _ in range(owned):
        start = text.rfind("\n", 0, start - 1) + 1

    return text[start : declaration_end(text, match.end(), name)]


def main() -> int:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <ChatMessage.kt> <out.kt>", file=sys.stderr)
        return 2
    source, out = sys.argv[1], sys.argv[2]
    with open(source, encoding="utf-8") as handle:
        text = handle.read()

    pieces = [HEADER]
    for name in WANTED:
        pieces.append(extract(text, name) + "\n\n")

    with open(out, "w", encoding="utf-8") as handle:
        handle.write("".join(pieces).rstrip() + "\n")
    print(f"extracted {', '.join(WANTED)} into {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
